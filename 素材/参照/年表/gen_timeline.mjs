function matrixRow(c) {
  const [id, name, tier, role, appear, exit] = c;
  const cells = [1, 2, 3, 4].map((p) => {
    const boxes = CHAPTERS.filter((ch) => ch.part === p).map((ch) => {
      const hit = ch.cast.find((x) => x[0] === id);
      if (!hit) return `<span class="cell" title="${label(ch)}（通し${ch.n}）"></span>`;
      const marks = hit[2] || "";
      const cls = ["cell", "on"];
      if (marks.includes("初")) cls.push("first");
      if (marks.includes("死")) cls.push("death");
      if (marks.includes("退")) cls.push("exit");
      if (marks.includes("仮")) cls.push("kari");
      const sym = marks.includes("死") ? "†" : marks.includes("退") ? "退" : marks.includes("初") ? "初" : "";
      const t = `${label(ch)}（通し${ch.n}）${hit[1] ? " " + hit[1] : ""}${marks.includes("仮") ? " 【仮】" : ""}`;
      return `<span class="${cls.join(" ")}" title="${esc(t)}">${sym}</span>`;
    });
    return `<td class="mcell"><div class="strip">${boxes.join("")}</div></td>`;
  });
  return `<tr data-char="${id}" class="t-${tier}">
  <th scope="row"><button type="button" class="mname" data-char="${id}"><span class="cid">${id}</span><span class="cname">${esc(name)}</span></button><span class="tier">${TIER_LABEL[tier]}</span></th>
  ${cells.join("")}
  <td class="mrole">${esc(role)}<span class="mappear">${esc(appear)}${exit !== "—" ? " ／ " + esc(exit) : ""}</span></td>
</tr>`;
}

