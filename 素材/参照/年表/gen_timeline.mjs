const JS = `
(function(){
  var NAMES = ${JSON.stringify(NAMES)};
  var FNAMES = ${JSON.stringify(FNAMES)};
  var cards = Array.prototype.slice.call(document.querySelectorAll('.ch[data-ch]'));
  var partBlocks = Array.prototype.slice.call(document.querySelectorAll('.part[data-part], .band[data-part]'));
  var jump = document.getElementById('jump');
  var pfButtons = Array.prototype.slice.call(document.querySelectorAll('.pf button'));
  var hlbar = document.getElementById('hlbar');
  var hltext = document.getElementById('hltext');
  var hlcount = document.getElementById('hlcount');
  var clearBtn = document.getElementById('hlclear');
  var state = { part: 'all', hl: null };

  function has(list, id){ return (' ' + (list || '') + ' ').indexOf(' ' + id + ' ') >= 0; }
  function matches(card){
    if (!state.hl) return true;
    if (state.hl.type === 'char') return has(card.getAttribute('data-chars'), state.hl.id);
    return has(card.getAttribute('data-fs'), state.hl.id);
  }
  function partOk(p){ return state.part === 'all' || String(p) === state.part; }

  function apply(){
    var n = 0;
    cards.forEach(function(card){
      var ok = partOk(card.getAttribute('data-part'));
      card.hidden = !ok;
      var m = matches(card);
      card.classList.toggle('dim', !!state.hl && !m);
      card.classList.toggle('hit', !!state.hl && m);
      if (ok && m && state.hl) n++;
    });
    partBlocks.forEach(function(el){ el.hidden = !partOk(el.getAttribute('data-part')); });
    if (jump) jump.hidden = !(state.part === 'all' || state.part === '3' || state.part === '4');
    pfButtons.forEach(function(b){ b.setAttribute('aria-pressed', b.getAttribute('data-part') === state.part ? 'true' : 'false'); });

    // pressed state on chips / badges / rows
    var hl = state.hl;
    Array.prototype.forEach.call(document.querySelectorAll('[data-char]'), function(el){
      var on = !!hl && hl.type === 'char' && el.getAttribute('data-char') === hl.id;
      if (el.tagName === 'BUTTON') el.setAttribute('aria-pressed', on ? 'true' : 'false');
      el.classList.toggle('hit', on);
    });
    Array.prototype.forEach.call(document.querySelectorAll('[data-f]'), function(el){
      var on = !!hl && hl.type === 'f' && el.getAttribute('data-f') === hl.id;
      if (el.tagName === 'BUTTON') el.setAttribute('aria-pressed', on ? 'true' : 'false');
      el.classList.toggle('hit', on);
    });

    if (hl){
      hlbar.hidden = false;
      hltext.textContent = hl.type === 'char' ? (hl.id + ' ' + (NAMES[hl.id] || '')) : (hl.id + ' ' + (FNAMES[hl.id] || ''));
      hlcount.textContent = '該当 ' + n + ' 章';
    } else {
      hlbar.hidden = true;
    }
  }

  function toggle(type, id){
    if (state.hl && state.hl.type === type && state.hl.id === id) state.hl = null;
    else state.hl = { type: type, id: id };
    apply();
  }

  document.addEventListener('click', function(ev){
    var t = ev.target;
    if (!(t instanceof Element)) return;
    var b = t.closest('button[data-char]');
    if (b){ toggle('char', b.getAttribute('data-char')); return; }
    var f = t.closest('button[data-f]');
    if (f){ toggle('f', f.getAttribute('data-f')); return; }
    var row = t.closest('tr[data-char]');
    if (row && !t.closest('a')){ toggle('char', row.getAttribute('data-char')); return; }
    var frow = t.closest('tr[data-f]');
    if (frow && !t.closest('a')){ toggle('f', frow.getAttribute('data-f')); return; }
    var p = t.closest('.pf button');
    if (p){ state.part = p.getAttribute('data-part'); apply(); return; }
    if (t.closest('#hlclear')){ state.hl = null; apply(); }
  });
  document.addEventListener('keydown', function(ev){
    if (ev.key === 'Escape' && state.hl){ state.hl = null; apply(); }
  });

  // 起動時: JS が効く印として行にカーソルを付ける
  document.documentElement.classList.add('js');
  apply();
})();
`;

